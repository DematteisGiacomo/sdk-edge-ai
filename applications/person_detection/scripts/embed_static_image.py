"""Embed a 128x128 RGB565 BE frame for PERSON_DET static-input builds."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

CAM_W = 128
CAM_H = 128


def rgb_to_rgb565_be(r: int, g: int, b: int) -> tuple[int, int]:
    r5 = (r >> 3) & 0x1F
    g6 = (g >> 2) & 0x3F
    b5 = (b >> 3) & 0x1F
    pix = (r5 << 11) | (g6 << 5) | b5
    return (pix >> 8) & 0xFF, pix & 0xFF


def load_rgb888(path: Path):
    try:
        from PIL import Image
    except ImportError as exc:
        raise SystemExit("Install Pillow: pip install pillow") from exc

    img = Image.open(path).convert("RGB")
    img = img.resize((CAM_W, CAM_H), Image.Resampling.LANCZOS)
    return img.load()


def write_header(out_path: Path, pixels_hi_lo: list[tuple[int, int]]) -> None:
    if len(pixels_hi_lo) != CAM_W * CAM_H:
        raise ValueError("wrong pixel count")

    lines = [
        "/* Auto-generated by scripts/embed_static_image.py — do not edit. */",
        "#pragma once",
        "",
        f"#define STATIC_IMAGE_RGB565_WIDTH  {CAM_W}",
        f"#define STATIC_IMAGE_RGB565_HEIGHT {CAM_H}",
        f"#define STATIC_IMAGE_RGB565_BYTES  ({CAM_W} * {CAM_H} * 2)",
        "",
        "static const uint8_t static_image_rgb565[STATIC_IMAGE_RGB565_BYTES] = {",
    ]

    row = "    "
    for i, (hi, lo) in enumerate(pixels_hi_lo):
        row += f"0x{hi:02x}, 0x{lo:02x}, "
        if (i + 1) % 8 == 0:
            lines.append(row.rstrip())
            row = "    "
    if row.strip():
        lines.append(row.rstrip().rstrip(","))

    lines.append("};")
    lines.append("")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {out_path} ({CAM_W}x{CAM_H} RGB565 BE, {len(pixels_hi_lo) * 2} bytes)")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "image",
        nargs="?",
        type=Path,
        help="Input photo (PNG/JPEG/…). Omit for a neutral gray placeholder.",
    )
    ap.add_argument(
        "-o",
        "--output",
        type=Path,
        default=Path(__file__).resolve().parent.parent / "src/generated/static_image_rgb565.h",
    )
    args = ap.parse_args()

    pixels: list[tuple[int, int]] = []

    if args.image is None:
        for _ in range(CAM_W * CAM_H):
            pixels.append(rgb_to_rgb565_be(128, 128, 128))
    else:
        px = load_rgb888(args.image)
        for y in range(CAM_H):
            for x in range(CAM_W):
                r, g, b = px[x, y]
                pixels.append(rgb_to_rgb565_be(r, g, b))

    write_header(args.output, pixels)
    return 0


if __name__ == "__main__":
    sys.exit(main())
